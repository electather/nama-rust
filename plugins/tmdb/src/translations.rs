/// Every translation as a choice of the Language setting, in tag order.
pub(crate) fn choices() -> Vec<Choice> {
    (TRANSLATIONS.iter())
        .map(|&(value, label)| Choice {
            value: value.to_owned(),
            label: label.to_owned(),
        })
        .collect()
}
